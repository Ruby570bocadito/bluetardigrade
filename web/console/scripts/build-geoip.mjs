const atlas = JSON.parse(readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'))
const centroids = {}
const unmatched = []
for (const f of feature(atlas, atlas.objects.countries).features) {
  const name = (f.properties?.name ?? '').toLowerCase()
  const cc = name in ALIASES ? ALIASES[name] : byName.get(name)
  if (cc === null) continue
  if (!cc) {
    unmatched.push(f.properties?.name)
    continue
  }
  const polygons = f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates]
  const largest = polygons
    .map((coordinates) => ({ type: 'Polygon', coordinates }))
    .reduce((best, p) => (geoArea(p) > geoArea(best) ? p : best))
  const [lon, lat] = geoCentroid(largest)
  centroids[cc] = [Math.round(lat * 100) / 100, Math.round(lon * 100) / 100]
}
