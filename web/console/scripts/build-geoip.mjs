// Builds the console's offline IP geolocation from DB-IP's free
// "IP to Country Lite" database (CC BY 4.0, https://db-ip.com):
//
//   src/lib/geo/dbip-ipv4.ts           IPv4 ranges -> country, compacted and
//                                      embedded (base64 of gzip), so every way
//                                      of running the console carries it
//   src/lib/geo/LICENSE-DBIP.txt       the attribution the licence asks for
//   src/lib/geo/country-centroids.ts   where each country is drawn on the map
//                                      (Natural Earth via world-atlas)
//
// The console never asks a service where an IP is: the lookup runs on the
// console server against this table (lib/geo/ip-country.ts).
//
// Run from web/console with the monthly file (download it from
// https://db-ip.com/db/download/ip-to-country-lite):
//   node scripts/build-geoip.mjs path/to/dbip-country-lite-YYYY-MM.csv.gz
// (dev dependencies: world-atlas, topojson-client, d3-geo)
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { basename, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { gunzipSync, gzipSync } from 'node:zlib'
import { feature } from 'topojson-client'
import { geoArea, geoCentroid } from 'd3-geo'

const source = process.argv[2]
if (!source) {
  console.error('uso: node scripts/build-geoip.mjs dbip-country-lite-YYYY-MM.csv.gz')
  process.exit(1)
}
const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const require = createRequire(import.meta.url)

// ---- 1. IPv4 ranges -> country, contiguous ranges of one country merged
const ipToInt = (ip) => ip.split('.').reduce((n, part) => n * 256 + Number(part), 0)
const csv = gunzipSync(readFileSync(source)).toString('utf8')
const codes = ['--'] // index 0: no country (reserved or unallocated)
const codeIndex = new Map([['--', 0]])
const starts = []
const owners = []
let expected = 0
for (const line of csv.split('\n')) {
  const [from, to, raw] = line.trim().split(',')
  if (!from || !from.includes('.')) continue
  const cc = raw === 'ZZ' ? '--' : raw
  if (!codeIndex.has(cc)) {
    codeIndex.set(cc, codes.length)
    codes.push(cc)
  }
  const start = ipToInt(from)
  if (start > expected) {
    // a hole in the file: nobody owns it
    starts.push(expected)
    owners.push(0)
  }
  const owner = codeIndex.get(cc)
  if (owners.length === 0 || owners[owners.length - 1] !== owner) {
    starts.push(start)
    owners.push(owner)
  }
  expected = ipToInt(to) + 1
}
if (codes.length > 255) throw new Error('more than 255 countries: the table stores one byte per range')

// layout: "BTGEO2" | uint32 count | count x uint32 start delta | count x uint8 country | uint8 n | n x 2 ascii
// (each start as the distance from the previous one: gzip packs those far better)
const count = starts.length
const table = Buffer.alloc(6 + 4 + count * 5 + 1 + codes.length * 2)
table.write('BTGEO2', 0, 'ascii')
table.writeUInt32LE(count, 6)
starts.forEach((s, i) => table.writeUInt32LE(s - (i ? starts[i - 1] : 0), 10 + i * 4))
owners.forEach((o, i) => table.writeUInt8(o, 10 + count * 4 + i))
table.writeUInt8(codes.length, 10 + count * 5)
codes.forEach((c, i) => table.write(c, 11 + count * 5 + i * 2, 'ascii'))
const geoDir = join(root, 'src', 'lib', 'geo')
mkdirSync(geoDir, { recursive: true })
writeFileSync(
  join(geoDir, 'dbip-ipv4.ts'),
  `// Generated by scripts/build-geoip.mjs from ${basename(source)}
// (IP Geolocation by DB-IP, https://db-ip.com, CC BY 4.0: see LICENSE-DBIP.txt).
// IPv4 ranges and their country, gzip in base64; read by ip-country.ts.
// Do not edit by hand: download a newer file and run the script again.
export const DBIP_IPV4 =
  '${gzipSync(table, { level: 9 }).toString('base64')}'
`,
)
writeFileSync(
  join(geoDir, 'LICENSE-DBIP.txt'),
  `IP Geolocation by DB-IP (https://db-ip.com)

dbip-ipv4.ts is built from ${basename(source)}, the free
"IP to Country Lite" database of DB-IP, licensed under the Creative Commons
Attribution 4.0 International licence (https://creativecommons.org/licenses/by/4.0/).
The console reshapes it (IPv4 only, contiguous ranges of one country merged)
with scripts/build-geoip.mjs; the country of every range is DB-IP's.
`,
)

