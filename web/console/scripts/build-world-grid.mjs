// Generates src/lib/v2/world-grid.ts from Natural Earth (world-atlas,
// public-domain geography): a regular grid over the world with one bit
// per cell that falls on land, for the dotted map of the command center.
// The console never fetches map tiles: a self-hosted SOC works offline
// and its CSP only allows its own origin.
//
// Run from web/console after changing the grid below:
//   node scripts/build-world-grid.mjs
// (dev dependencies: world-atlas, topojson-client, d3-geo)
import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { feature } from 'topojson-client'
import { geoBounds, geoContains } from 'd3-geo'

const STEP = 2 // degrees per cell
const LAT_TOP = 84 // the grid leaves Antarctica out
const LAT_BOTTOM = -58
const COLS = 360 / STEP
const ROWS = (LAT_TOP - LAT_BOTTOM) / STEP

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
const atlas = JSON.parse(readFileSync(require.resolve('world-atlas/land-50m.json'), 'utf8'))
const land = feature(atlas, atlas.objects.land)

// one polygon per ring, each with its bounding box, so a point only meets
// the polygons around it
const polygons = (land.features ?? [land])
  .map((f) => f.geometry)
  .flatMap((g) => (g.type === 'MultiPolygon' ? g.coordinates : [g.coordinates]))
  .map((coordinates) => {
    const polygon = { type: 'Polygon', coordinates }
    const [[x0, y0], [x1, y1]] = geoBounds(polygon)
    return { polygon, x0, y0, x1, y1 }
  })

function inBounds(p, lon, lat) {
  if (lat < p.y0 - 1e-9 || lat > p.y1 + 1e-9) return false
  // geoBounds reports x0 > x1 for a polygon that crosses the antimeridian
  return p.x0 <= p.x1 ? lon >= p.x0 && lon <= p.x1 : lon >= p.x0 || lon <= p.x1
}

const onLand = (lon, lat) => polygons.some((p) => inBounds(p, lon, lat) && geoContains(p.polygon, [lon, lat]))

// a cell is land when its center or one of four inner points is: keeps
// islands and narrow coasts (Japan, Italy, Chile) on a 2-degree grid
const q = STEP / 4
const SAMPLES = [[0, 0], [-q, -q], [q, -q], [-q, q], [q, q]]
const mask = new Uint8Array(Math.ceil((COLS * ROWS) / 8))
let landCells = 0
for (let r = 0; r < ROWS; r++) {
  const lat = LAT_TOP - (r + 0.5) * STEP
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + (c + 0.5) * STEP
    if (SAMPLES.some(([dx, dy]) => onLand(lon + dx, lat + dy))) {
      const i = r * COLS + c
      mask[i >> 3] |= 1 << (i & 7)
      landCells++
    }
  }
}

const out = join(here, '..', 'src', 'lib', 'v2', 'world-grid.ts')
writeFileSync(
  out,
  `// Generated by scripts/build-world-grid.mjs from Natural Earth (world-atlas,
// public domain). Do not edit by hand: change the script and run it again.
export const GRID_STEP = ${STEP}
export const GRID_LAT_TOP = ${LAT_TOP}
export const GRID_COLS = ${COLS}
export const GRID_ROWS = ${ROWS}
/** One bit per cell, row by row from the north-west corner (bit i of byte i >> 3): 1 = land. */
export const LAND_GRID = '${Buffer.from(mask).toString('base64')}'
`,
)
console.log(`${out}: ${COLS} x ${ROWS} cells, ${landCells} on land`)
